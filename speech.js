function spoken(t){ for(const [re,to] of READ) t=t.replace(re,to); return t; }
// 1文ずつに分ける（文ごとに音声ファイルを用意する）
function toSentences(text){ return (spoken(text).match(/[^。！？]*[。！？]?/g)||[]).map(x=>x.trim()).filter(x=>/[^\s）)」』、。！？]/.test(x)); }   // 「）」だけの断片は読まない
// 音声ファイル名（FNV-1a ハッシュ）
function clipId(s){ let h=0x811c9dc5; for(let i=0;i<s.length;i++){ h^=s.charCodeAt(i); h=Math.imul(h,0x01000193)>>>0; } return h.toString(16).padStart(8,'0'); }
